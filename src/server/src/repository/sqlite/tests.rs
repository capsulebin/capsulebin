/// The timestamp is coarse. A burst of retrievals must cost one timestamp write,
/// otherwise the granularity setting buys nothing.
#[tokio::test]
async fn the_retrieval_timestamp_is_coarse() {
    let repo = repository("retrieval-granularity").await;
    let granularity = 3_600;
    repo.create(&new_paste(id(3), 1_000, None)).await.expect("create");

    repo.track_retrieval(&id(3), 10_000, granularity).await.expect("first");
    repo.track_retrieval(&id(3), 11_000, granularity).await.expect("within window");
    repo.track_retrieval(&id(3), 13_599, granularity).await.expect("still within");

    let paste = repo.find(&id(3)).await.expect("find").expect("present");
    assert_eq!(
        paste.last_retrieved_at,
        Some(10_000),
        "the timestamp must not move inside the window"
    );

    // One second past the window it moves again.
    repo.track_retrieval(&id(3), 13_600, granularity).await.expect("after the window");

    let paste = repo.find(&id(3)).await.expect("find").expect("present");
    assert_eq!(paste.last_retrieved_at, Some(13_600));
}

