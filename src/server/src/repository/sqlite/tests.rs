/// 20 truly concurrent callers race for the same burn-after-retrieval paste.
/// A deferred `BEGIN` lets every caller read the row before any of them
/// writes, so most lose with a raw `SQLITE_BUSY_SNAPSHOT` instead of a clean
/// `None` — this is what `BEGIN IMMEDIATE` in the implementation prevents.
#[tokio::test]
async fn concurrent_burn_calls_yield_exactly_one_some() {
    let repo = repository("burn-concurrent").await;
    let now = 1_000;

    repo.create(&new_burn_paste(id(1), now, None)).await.expect("create");

    let mut handles = Vec::new();
    for _ in 0..20 {
        let repo = repo.clone();
        handles.push(tokio::spawn(async move { repo.retrieve_and_burn(&id(1), now).await }));
    }

    let mut successes = 0;
    for handle in handles {
        if handle.await.expect("task").expect("no db error").is_some() {
            successes += 1;
        }
    }

    assert_eq!(successes, 1, "exactly one concurrent caller must win the burn");
}

