//! Repository tests against a real SQLite file.
//!
//! Not an in-memory database: WAL, the busy timeout and the unique constraint are
//! exactly the things these tests need to exercise, and an in-memory database
//! behaves differently for all three.

// `Row` (for `try_get`) comes in through `super::*`.
use super::*;
use crate::config::{DatabaseConfig, Synchronous};
use crate::domain::clock::{Clock as _, FixedClock};

/// Thresholds used by the purge tests: 30 days without a retrieval, 90 days
/// without a recent one. The same values the example configuration ships.
const POLICY: PurgePolicy = PurgePolicy {
    never_retrieved_after: 30 * 86_400,
    inactive_after: 90 * 86_400,
};

/// A granularity of zero makes every retrieval advance the timestamp, which is
/// what a test that is not about coarseness wants.
const EXACT: i64 = 0;

async fn repository(name: &str) -> SqlitePasteRepository {
    let dir = std::env::temp_dir().join(format!("capsulebin-repo-{name}"));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create temp dir");

    let pool = crate::db::connect(&DatabaseConfig {
        path: dir.join("capsulebin.db"),
        busy_timeout_ms: 5_000,
        synchronous: Synchronous::Full,
    })
    .await
    .expect("connect");

    SqlitePasteRepository::new(pool)
}

fn id(byte: u8) -> PasteId {
    PasteId::from_bytes([byte; 16])
}

fn new_paste(id: PasteId, created_at: i64, expires_at: Option<i64>) -> NewPaste {
    NewPaste {
        id,
        format_version: 1,
        public_header: vec![0xAA, 0xBB],
        ciphertext: vec![1, 2, 3, 4, 5],
        reveal_verifier: Verifier::for_reveal_token(b"reveal"),
        delete_verifier: Verifier::for_delete_secret(b"delete"),
        describe_verifier: Verifier::for_describe_token(b"describe"),
        created_at,
        expires_at,
        burn_after_retrieval: false,
    }
}

fn new_burn_paste(id: PasteId, created_at: i64, expires_at: Option<i64>) -> NewPaste {
    NewPaste {
        burn_after_retrieval: true,
        ..new_paste(id, created_at, expires_at)
    }
}

#[tokio::test]
async fn stores_and_loads_a_paste_byte_exactly() {
    let repo = repository("round-trip").await;
    let clock = FixedClock::at(1_000);

    let created = repo.create(&new_paste(id(1), clock.now(), Some(2_000))).await.expect("create");

    let loaded = repo.find(&id(1)).await.expect("find").expect("present");

    // The public header is authenticated as additional data by the client, so a
    // single flipped byte would make every capsule undecryptable.
    assert_eq!(loaded.public_header, vec![0xAA, 0xBB]);
    assert_eq!(loaded.ciphertext.as_deref(), Some([1, 2, 3, 4, 5].as_slice()));
    assert_eq!(loaded.payload_size, 5);
    assert_eq!(loaded.created_at, 1_000);
    assert_eq!(loaded.expires_at, Some(2_000));
    assert_eq!(loaded.availability, Availability::Active);
    assert!(!loaded.burn_after_retrieval);
    // A capsule nobody has fetched carries no retrieval timestamp. NULL rather
    // than the creation time, because the purge rules distinguish the two.
    assert_eq!(loaded.last_retrieved_at, None);

    // Verifiers survive the round trip, otherwise no capability would ever match.
    assert!(loaded.reveal_verifier.matches(&created.reveal_verifier));
    assert!(loaded.delete_verifier.matches(&Verifier::for_delete_secret(b"delete")));
}

