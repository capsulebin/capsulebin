/// Deleting keeps a tombstone: the row stays, the payload goes. Dropping the row
/// entirely would make a deleted paste indistinguishable from one that never
/// existed - which sounds desirable but breaks the "already retrieved" answer for
/// burn pastes.
#[tokio::test]
async fn delete_drops_the_payload_and_keeps_a_tombstone() {
    let repo = repository("delete").await;
    repo.create(&new_paste(id(4), 1_000, None)).await.expect("create");

    assert!(repo.delete(&id(4)).await.expect("delete"));

    let tombstone = repo.find(&id(4)).await.expect("find").expect("row remains");
    assert_eq!(tombstone.availability, Availability::Deleted);
    assert!(tombstone.ciphertext.is_none(), "ciphertext must be gone");
    assert!(!tombstone.is_retrievable(1_600));
    // The header is retained; it carries no plaintext and helps diagnostics.
    assert_eq!(tombstone.public_header, vec![0xAA, 0xBB]);
}

