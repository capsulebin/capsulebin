/// Expiry is evaluated against the injected clock, which is the whole reason the
/// `Clock` trait exists: this test covers a 90-day lifetime in microseconds.
#[tokio::test]
async fn purge_removes_only_what_is_due() {
    let repo = repository("purge").await;
    let clock = FixedClock::at(1_000);

    repo.create(&new_paste(id(1), clock.now(), Some(2_000)))
        .await
        .expect("expires soon");
    repo.create(&new_paste(id(2), clock.now(), Some(9_000)))
        .await
        .expect("expires later");
    repo.create(&new_paste(id(3), clock.now(), None)).await.expect("never expires");

    // Nothing is due yet.
    assert!(repo.purge(clock.now(), &POLICY, 100).await.expect("purge").is_empty());

    clock.set(2_000);
    let outcome = repo.purge(clock.now(), &POLICY, 100).await.expect("purge");
    assert_eq!(outcome.expired, 1, "the paste expiring at 2000 must be purged at 2000, not at 2001");
    assert_eq!(outcome.total(), 1, "only the expiry rule may fire this early");

    assert!(
        repo.find(&id(1)).await.expect("find").is_none(),
        "the expired row must be gone, not tombstoned: its retention metadata has to go with it"
    );
    assert!(
        repo.find(&id(2)).await.expect("find").is_some(),
        "a paste expiring later must survive"
    );
    assert!(
        repo.find(&id(3)).await.expect("find").is_some(),
        "a paste without an expiry must survive the expiry rule"
    );

    // Running again finds nothing new, so repeated cleanup converges.
    assert!(repo.purge(clock.now(), &POLICY, 100).await.expect("purge").is_empty());
}

/// An explicit expiry wins over recency: the creator said when the capsule should
/// go, and a retrieval a second ago does not extend that.
#[tokio::test]
async fn an_explicit_expiry_beats_recent_activity() {
    let repo = repository("purge-expiry-wins").await;
    repo.create(&new_paste(id(1), 1_000, Some(2_000))).await.expect("create");
    repo.track_retrieval(&id(1), 1_900, EXACT).await.expect("retrieved");

    let outcome = repo.purge(2_000, &POLICY, 100).await.expect("purge");

    assert_eq!(outcome.expired, 1);
    assert!(repo.find(&id(1)).await.expect("find").is_none());
}

/// A capsule nobody ever fetched ages out from its creation - including one created
/// without an expiry. "No fixed expiry" is not "kept forever".
#[tokio::test]
async fn purge_removes_capsules_that_were_never_retrieved() {
    let repo = repository("purge-never-retrieved").await;
    let created = 1_000_000;
    repo.create(&new_paste(id(1), created, None)).await.expect("permanent");

    let just_before = created + POLICY.never_retrieved_after - 1;
    assert!(
        repo.purge(just_before, &POLICY, 100).await.expect("purge").is_empty(),
        "must survive right up to the threshold"
    );

    let outcome = repo
        .purge(created + POLICY.never_retrieved_after, &POLICY, 100)
        .await
        .expect("purge");

    assert_eq!(outcome.never_retrieved, 1);
    assert_eq!(outcome.total(), 1);
    assert!(repo.find(&id(1)).await.expect("find").is_none());
}

/// Once a capsule has been retrieved, inactivity is measured from the retrieval and
/// the creation date stops mattering - otherwise a capsule in daily use would be
/// deleted on its 30th day.
#[tokio::test]
async fn purge_measures_a_retrieved_capsule_from_its_last_retrieval() {
    let repo = repository("purge-inactive").await;
    let created = 1_000_000;
    let retrieved = created + 10;

    repo.create(&new_paste(id(1), created, None)).await.expect("create");
    repo.track_retrieval(&id(1), retrieved, EXACT).await.expect("retrieve");

    // Well past never_retrieved_after, but the retrieval moved it to the other rule.
    let past_creation_rule = created + POLICY.never_retrieved_after + 1;
    assert!(
        repo.purge(past_creation_rule, &POLICY, 100).await.expect("purge").is_empty(),
        "a retrieved capsule must not be judged by its creation date"
    );

    let outcome = repo.purge(retrieved + POLICY.inactive_after, &POLICY, 100).await.expect("purge");

    assert_eq!(outcome.inactive, 1);
    assert!(repo.find(&id(1)).await.expect("find").is_none());
}

#[tokio::test]
async fn purge_keeps_a_recently_retrieved_capsule() {
    let repo = repository("purge-active").await;
    let created = 1_000_000;
    let now = created + POLICY.inactive_after * 2;

    repo.create(&new_paste(id(1), created, None)).await.expect("create");
    repo.track_retrieval(&id(1), now - 60, EXACT).await.expect("retrieve");

    assert!(
        repo.purge(now, &POLICY, 100).await.expect("purge").is_empty(),
        "a capsule retrieved a minute ago must survive any retention rule"
    );
    assert!(repo.find(&id(1)).await.expect("find").is_some());
}

#[tokio::test]
async fn purge_respects_the_batch_limit() {
    let repo = repository("purge-limit").await;

    for byte in 1..=5 {
        repo.create(&new_paste(id(byte), 1_000, Some(2_000))).await.expect("create");
    }

    // The limit applies per rule per call, so five due rows take three rounds of
    // two - which is exactly how the caller learns when to stop.
    assert_eq!(repo.purge(3_000, &POLICY, 2).await.expect("purge").expired, 2);
    assert_eq!(repo.purge(3_000, &POLICY, 2).await.expect("purge").expired, 2);
    assert_eq!(repo.purge(3_000, &POLICY, 2).await.expect("purge").expired, 1);
    assert!(repo.purge(3_000, &POLICY, 2).await.expect("purge").is_empty());
}

/// Each rule reports separately: an aggregate would hide a deployment whose
/// inactivity threshold is removing far more than the operator expected.
#[tokio::test]
async fn purge_reports_each_rule_separately() {
    let repo = repository("purge-rules").await;
    let created = 1_000_000;
    let now = created + POLICY.never_retrieved_after + POLICY.inactive_after + 1;

    repo.create(&new_paste(id(1), created, Some(created + 10))).await.expect("expired");
    repo.create(&new_paste(id(2), created, None)).await.expect("never retrieved");
    repo.create(&new_paste(id(3), created, None)).await.expect("inactive");
    repo.track_retrieval(&id(3), created + 20, EXACT).await.expect("retrieve");

    let outcome = repo.purge(now, &POLICY, 100).await.expect("purge");

    assert_eq!(outcome.expired, 1);
    assert_eq!(outcome.never_retrieved, 1);
    assert_eq!(outcome.inactive, 1);
}

