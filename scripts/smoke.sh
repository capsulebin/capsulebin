# --- abuse reports and moderation --------------------------------------------
#
# A report about an existing paste and one about an unknown id get the same
# answer, only the first reaches the queue. The operator CLI then disables,
# restores and deletes the paste, and the public API must treat a moderated
# paste exactly like an unknown one - even for a caller holding the reveal token.

POLICY="$(curl -fsS "${API%/pastes}/reports")" || fail "GET /api/v1/reports failed"
grep -q '"enabled":true' <<<"${POLICY}" || fail "reports are not enabled by default: ${POLICY}"
echo "ok  report policy"

MOD_ID="2pS3xQ7Rk9mNpLz4AbCdEw"
CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "${API}" \
  -H 'content-type: application/json' \
  -H "authorization: Bearer ${TOKEN}" \
  --data "$(create_body "${MOD_ID}")")"
[ "${CODE}" = "201" ] || fail "could not create the paste for the moderation check (${CODE})"

report_body() {
  printf '{"paste_id":"%s","reason":"phishing","description":"smoke test report"}' "$1"
}
REPORTED="$(curl -sS -w ' %{http_code}' -X POST "${API%/pastes}/reports" \
  -H 'content-type: application/json' --data "$(report_body "${MOD_ID}")")"
UNKNOWN="$(curl -sS -w ' %{http_code}' -X POST "${API%/pastes}/reports" \
  -H 'content-type: application/json' --data "$(report_body "AAAAAAAAAAAAAAAAAAAAAA")")"
[ "${REPORTED}" = "${UNKNOWN}" ] || fail "report answers differ by id: '${REPORTED}' vs '${UNKNOWN}'"
grep -q ' 202$' <<<"${REPORTED}" || fail "a report was not accepted: ${REPORTED}"
echo "ok  reports are answered identically for existing and unknown ids"

QUEUE="$("${BINARY}" reports list --json)" || fail "reports list failed"
[ "$(grep -o '"paste_id":"[^"]*"' <<<"${QUEUE}" | sort -u)" = "\"paste_id\":\"${MOD_ID}\"" ] ||
  fail "the queue should hold exactly the report about the existing paste: ${QUEUE}"
REPORT_ID="$(sed -n 's/.*"id":"\([0-9A-Z]\{26\}\)".*/\1/p' <<<"${QUEUE}")"
[ -n "${REPORT_ID}" ] || fail "could not read the report id: ${QUEUE}"
echo "ok  reports list shows only the report about an existing paste"

retrieve_code() {
  curl -s -o /dev/null -w '%{http_code}' -X POST "${API}/${MOD_ID}/retrieve" \
    -H 'content-type: application/json' \
    --data "$(retrieve_body)"
}

"${BINARY}" moderation disable "${MOD_ID}" --reason phishing --note "smoke" >/dev/null ||
  fail "moderation disable failed"
[ "$(retrieve_code)" = "404" ] || fail "a disabled paste is still retrievable"
echo "ok  a disabled paste is not retrievable, even with the reveal token"

"${BINARY}" moderation restore "${MOD_ID}" >/dev/null || fail "moderation restore failed"
[ "$(retrieve_code)" = "200" ] || fail "a restored paste is not retrievable"
echo "ok  restore makes it available again"

"${BINARY}" moderation delete "https://paste.example/p/${MOD_ID}#v1.ignored" --reason phishing >/dev/null ||
  fail "moderation delete (given a link) failed"
[ "$(retrieve_code)" = "404" ] || fail "a deleted paste is still retrievable"
if "${BINARY}" moderation restore "${MOD_ID}" >/dev/null 2>&1; then
  fail "a deleted paste was restored"
fi
STATUS="$("${BINARY}" moderation status "${MOD_ID}" --json)" || fail "moderation status failed"
grep -q '"status":"deleted"' <<<"${STATUS}" || fail "unexpected status: ${STATUS}"
[ "$(grep -o '"action":"[a-z]*"' <<<"${STATUS}" | tr '\n' ' ')" = '"action":"disable" "action":"restore" "action":"delete" ' ] ||
  fail "the audit trail is incomplete: ${STATUS}"
echo "ok  delete is final and the audit trail records every action"

"${BINARY}" reports close "${REPORT_ID}" --resolution action_taken >/dev/null || fail "reports close failed"
[ "$("${BINARY}" reports list --json)" = "[]" ] || fail "a closed report is still listed as open"
echo "ok  reports close"

# --- backup and restore ------------------------------------------------------
#
# A backup of the live database while the server is serving, then a restore into
# a second location - the way an operator moves an instance.

BACKUP="${WORKDIR}/backup.db"
"${BINARY}" backup --output "${BACKUP}" >/dev/null || fail "backup failed while the server is running"
[ ! -e "${BACKUP}-wal" ] || fail "the backup came with a -wal file"
[ "$(stat -c '%a' "${BACKUP}")" = "600" ] || fail "the backup is readable by others ($(stat -c '%a' "${BACKUP}"))"
if "${BINARY}" backup --output "${BACKUP}" >/dev/null 2>&1; then
  fail "backup overwrote an existing file"
fi
for secret in "${REVEAL_TOKEN}" "${DELETE_SECRET}" "${TOKEN}"; do
  if grep -qa -- "${secret}" "${BACKUP}"; then
    fail "a capability secret was written to the backup"
  fi
done
echo "ok  backup of a live database (owner-only, no WAL, no secrets, never overwrites)"

"${BINARY}" restore --input "${BACKUP}" --dry-run | grep -q '^ok: .* is a usable backup' ||
  fail "restore --dry-run rejected the backup"
RESTORED="${WORKDIR}/restored/capsulebin.db"
mkdir -p "$(dirname "${RESTORED}")"
CAPSULEBIN__DATABASE__PATH="${RESTORED}" "${BINARY}" restore --input "${BACKUP}" >/dev/null ||
  fail "restore into an empty location failed"
CAPSULEBIN__DATABASE__PATH="${RESTORED}" "${BINARY}" moderation status "${MOD_ID}" --json |
  grep -q '"status":"deleted"' || fail "the restored database lacks the moderation state"
if CAPSULEBIN__DATABASE__PATH="${RESTORED}" "${BINARY}" restore --input "${BACKUP}" >/dev/null 2>&1; then
  fail "restore replaced an existing database without --force"
fi
CAPSULEBIN__DATABASE__PATH="${RESTORED}" "${BINARY}" restore --input "${BACKUP}" --force >/dev/null ||
  fail "restore --force failed"
ls "${RESTORED}".pre-restore-* >/dev/null 2>&1 || fail "restore --force did not keep the previous database"
echo "ok  restore (verified, refuses to overwrite, --force keeps the previous file)"

# --- prune -------------------------------------------------------------------
#
# The retention policy against the real binary, while the server holds the same
# database open - which is the interesting part: two processes, one write-ahead log.
#
# A capsule with a one-second expiry is due almost immediately; the capsule created
# earlier in this run is not. One invocation therefore shows both halves of the
# rule, and the per-rule counts show that the right one fired.

PRUNE_ID="2pS3xQ7Rk9mNpLz4AbCdEQ"

CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "${API}" \
  -H 'content-type: application/json' \
  -H "authorization: Bearer ${TOKEN}" \
  --data "$(create_body "${PRUNE_ID}" 1)")"
[ "${CODE}" = "201" ] || fail "could not create the capsule for the prune check (${CODE})"

sleep 2

PRUNED="$("${BINARY}" prune)" || fail "prune failed: ${PRUNED}"
grep -q '^ok: 1 capsule(s) removed (1 expired, 0 never retrieved, 0 inactive)$' <<<"${PRUNED}" ||
  fail "prune removed the wrong set: ${PRUNED}"
echo "ok  prune removes the expired capsule and nothing else"

# A second run has nothing left to do. Purging deletes rows rather than tombstoning
# them, so a repeat must not find the same capsule again.
PRUNED="$("${BINARY}" prune)" || fail "the second prune failed: ${PRUNED}"
grep -q '^ok: 0 capsule(s) removed' <<<"${PRUNED}" || fail "prune is not idempotent: ${PRUNED}"
echo "ok  prune is idempotent"

