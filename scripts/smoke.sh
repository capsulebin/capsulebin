#!/usr/bin/env bash
#
# Acceptance check against a real release binary.
#
# Covers what unit and integration tests cannot: that the shipped binary, with its
# embedded assets and embedded migrations, actually starts from configuration and
# serves a complete paste lifecycle over a real socket.
#
# Runs identically locally and in CI. Expects the path to the binary as argument.
#
#   ./scripts/smoke.sh ./target/release/capsulebin
#
# With CAPSULEBIN_CLI pointing at the bundled CLI (src/cli/dist/cli.js), the run
# also takes a capsule through `put`, `get` and `delete` against the binary - the
# real client crypto against the real server:
#
#   CAPSULEBIN_CLI=src/cli/dist/cli.js ./scripts/smoke.sh ./target/release/capsulebin
#
# Requires: curl, openssl, basenc (coreutils >= 8.31); node for the CLI part.
set -euo pipefail

BINARY="${1:?path to the capsulebin binary expected}"
PORT="${SMOKE_PORT:-18080}"
BASE="http://127.0.0.1:${PORT}"
WORKDIR="$(mktemp -d)"

fail() {
  echo "FAILED: $*" >&2
  exit 1
}

need() {
  command -v "$1" >/dev/null 2>&1 || fail "$1 is required but not installed"
}
need curl
need openssl
need basenc

# --- helpers -----------------------------------------------------------------

# base64url without padding, the encoding the API uses everywhere.
b64url() {
  basenc --base64url -w0 | tr -d '='
}

# SHA-256 of stdin, base64url encoded. This is how a capability verifier is built.
sha256_b64url() {
  openssl dgst -sha256 -binary | b64url
}

# Extracts a string field from a flat JSON object. Not a JSON parser - these
# responses are flat and generated by us, and requiring jq would add a dependency
# for nothing else.
json_field() {
  sed -n "s/.*\"$1\":\"\([^\"]*\)\".*/\1/p"
}

# check_headers <route> [curl arguments]: the security headers every response
# carries, whatever its status.
check_headers() {
  local route="$1"
  shift
  local headers
  headers="$(curl -sS -D - -o /dev/null "$@" "${BASE}${route}" | tr -d '\r' | tr 'A-Z' 'a-z')"

  expect_header() {
    grep -qi "^$1: $2\$" <<<"${headers}" ||
      fail "${route}: header '$1' is missing or differs (expected: $2)"
  }

  expect_header "referrer-policy" "no-referrer"
  expect_header "x-content-type-options" "nosniff"
  expect_header "x-frame-options" "deny"
  expect_header "x-robots-tag" "noindex, nofollow, noarchive"
  expect_header "permissions-policy" "camera=(), microphone=(), geolocation=()"

  grep -qi '^x-request-id: [0-9a-z]\{26\}$' <<<"${headers}" ||
    fail "${route}: missing or malformed request id"

  local csp
  csp="$(grep -i '^content-security-policy:' <<<"${headers}")" ||
    fail "${route}: no Content-Security-Policy"

  for directive in \
    "default-src 'none'" \
    "script-src 'self'" \
    "style-src 'self'" \
    "object-src 'none'" \
    "base-uri 'none'" \
    "frame-ancestors 'none'" \
    "require-trusted-types-for 'script'"; do
    grep -qF "${directive}" <<<"${csp}" || fail "${route}: CSP without \"${directive}\""
  done

  for forbidden in "unsafe-inline" "unsafe-eval" "http://" "https://" "*"; do
    if grep -qF "${forbidden}" <<<"${csp}"; then
      fail "${route}: CSP contains \"${forbidden}\""
    fi
  done
}

# --- configuration -----------------------------------------------------------
#
# Supplied through the environment rather than a file, so the run also exercises
# the CAPSULEBIN__ overlay.

# `capsulebin token` is the supported way to produce a token hash; parsing its
# output here puts that subcommand under test too.
TOKEN_OUTPUT="$("${BINARY}" token)" || fail "capsulebin token failed"
TOKEN="$(sed -n '2s/^ *//p' <<<"${TOKEN_OUTPUT}")"
TOKEN_HASH="$(grep -o 'sha256:[A-Za-z0-9_-]*' <<<"${TOKEN_OUTPUT}" | head -1)"

[ -n "${TOKEN}" ] || fail "could not read the generated token"
[ -n "${TOKEN_HASH}" ] || fail "could not read the generated token hash"

export CAPSULEBIN__SERVER__PUBLIC_URL="https://paste.example"
export CAPSULEBIN__SERVER__BIND="127.0.0.1:${PORT}"
export CAPSULEBIN__DATABASE__PATH="${WORKDIR}/capsulebin.db"
export CAPSULEBIN__CREATION__MODE="token"
export CAPSULEBIN__CREATION__TOKEN_HASHES="[\"${TOKEN_HASH}\"]"
# An operator, so that all three legal pages exist: the imprint from this text,
# privacy notice and terms built in.
LEGAL_MARKER="Smoke Operator, Example Street 1"
export CAPSULEBIN__LEGAL__OPERATOR__TEXT="${LEGAL_MARKER}"

# Must stay unset, otherwise the run would not prove the assets are embedded.
unset CAPSULEBIN__SERVER__ASSET_DIR

# --- check subcommand --------------------------------------------------------
#
# Before the server starts, because a deployment is supposed to be verifiable
# without opening a port.

"${BINARY}" check >/dev/null || fail "\`check\` rejected a valid configuration"
echo "ok  check"

# --- start -------------------------------------------------------------------

echo "== starting ${BINARY} on port ${PORT}"
"${BINARY}" serve &
SERVER_PID=$!

cleanup() {
  if kill -0 "${SERVER_PID}" 2>/dev/null; then
    kill "${SERVER_PID}" 2>/dev/null || true
    wait "${SERVER_PID}" 2>/dev/null || true
  fi
  rm -rf "${WORKDIR}"
}
trap cleanup EXIT

for _ in $(seq 1 50); do
  if curl -fsS -o /dev/null "${BASE}/health/live" 2>/dev/null; then
    break
  fi
  if ! kill -0 "${SERVER_PID}" 2>/dev/null; then
    fail "the server exited during startup"
  fi
  sleep 0.2
done

curl -fsS -o /dev/null "${BASE}/health/live" || fail "/health/live unreachable"
echo "ok  /health/live"

# ready proves the assets are embedded *and* the migrations ran.
READY="$(curl -sS "${BASE}/health/ready")"
grep -q '"database":"ok"' <<<"${READY}" || fail "/health/ready reports the database as unusable: ${READY}"
grep -q '"assets":"ok"' <<<"${READY}" ||
  fail "/health/ready reports missing assets; run \`npm run build\` in src/server/web/ before cargo build"
grep -q '"schema_version":3' <<<"${READY}" || fail "unexpected schema version: ${READY}"
echo "ok  /health/ready (assets embedded, schema applied)"

# The container health check: the binary probes its own endpoints, derived from
# CAPSULEBIN__SERVER__BIND, and must fail where nothing listens.
"${BINARY}" healthcheck >/dev/null || fail "\`healthcheck\` reported the running server as unhealthy"
"${BINARY}" healthcheck --live >/dev/null || fail "\`healthcheck --live\` reported the running server as unhealthy"
if "${BINARY}" healthcheck --address "127.0.0.1:$((PORT + 2))" >/dev/null 2>&1; then
  fail "\`healthcheck\` succeeded against a port nobody listens on"
fi
echo "ok  healthcheck"

# --- shells ------------------------------------------------------------------

VALID_ID="2pS3xQ7Rk9mNpLz4AbCdEA"

# Every page exists once per known language and in its language: without a
# prefix in the default language (en, nothing else is configured here), under
# its prefix in every other one. Each carries every known language and the
# default for the head script, and its internal links and the legal links in
# the footer under its own prefix; no token of the web build is left.
for lang in en de; do
  prefix=""
  [ "${lang}" = "en" ] || prefix="/${lang}"
  for route in "${prefix}/" "${prefix}/p/${VALID_ID}" "${prefix}/manage/${VALID_ID}" "${prefix}/report" \
    "${prefix}/imprint" "${prefix}/privacy" "${prefix}/terms"; do
    headers="$(curl -fsS -D - -o "${WORKDIR}/shell.html" "${BASE}${route}" | tr -d '\r')" ||
      fail "${route} unreachable"
    grep -qi '^content-type: text/html; charset=utf-8$' <<<"${headers}" || fail "${route} is not served as HTML"
    grep -qi '^cache-control: no-store$' <<<"${headers}" || fail "${route} may be cached"
    grep -q "<html lang=\"${lang}\">" "${WORKDIR}/shell.html" || fail "${route} is not a shell in '${lang}'"
    grep -qE '<meta name="capsulebin-languages" content="en de" data-default="en"[[:space:]]*/?>' \
      "${WORKDIR}/shell.html" ||
      fail "${route} does not carry the offered languages and the default"
    grep -q "href=\"${prefix}/imprint\"" "${WORKDIR}/shell.html" ||
      fail "${route} lacks the footer link to ${prefix}/imprint"
    grep -q "href=\"${prefix}/\"" "${WORKDIR}/shell.html" ||
      fail "${route} lacks the internal link to ${prefix}/"
    if grep -q '%%capsulebin:' "${WORKDIR}/shell.html"; then
      fail "${route} still carries a token of the web build"
    fi
    # The "Powered by" link to the source code is the one outgoing link; only the
    # project's name is linked, opened in a new tab.
    grep -qF '<a href="https://github.com/capsulebin/capsulebin" target="_blank" rel="noopener noreferrer">CapsuleBin</a>' \
      "${WORKDIR}/shell.html" ||
      fail "${route} lacks the link to the source code"
    grep -qE '<link rel="icon" href="/favicon.svg"[[:space:]]*/?>' "${WORKDIR}/shell.html" ||
      fail "${route} does not link the built-in favicon"
    if grep -oE '(src|href)="https?://[^"]*"' "${WORKDIR}/shell.html" |
      grep -qvF 'href="https://github.com/capsulebin/capsulebin"'; then
      fail "${route} references an external resource"
    fi
    check_headers "${route}"
    echo "ok  ${route}"
  done
  grep -q "${LEGAL_MARKER}" <<<"$(curl -fsS "${BASE}${prefix}/imprint")" ||
    fail "${prefix}/imprint does not show the configured text"
done

# The built-in privacy notice exists in every language, titled from the page's
# catalogue.
for expected in "/privacy|Privacy|GDPR" "/de/privacy|Datenschutz|DSGVO"; do
  IFS='|' read -r route title text <<<"${expected}"
  page="$(curl -fsS "${BASE}${route}")" || fail "${route} unreachable"
  grep -qF "<title>${title} · CapsuleBin</title>" <<<"${page}" || fail "${route} is not titled '${title}'"
  grep -qF "<h1>${title}</h1>" <<<"${page}" || fail "${route} lacks the heading '${title}'"
  grep -qF "${text}" <<<"${page}" || fail "${route} does not show the built-in text (no '${text}')"
  echo "ok  ${route} (built-in text, title '${title}')"
done

# The default language has no prefix: a path under it is redirected to the same
# path without it. The path is only copied, so the key in the fragment stays in
# the browser. The server does not negotiate: no Vary, and Accept-Language
# changes nothing.
for route in "" "/" "/p/${VALID_ID}" "/report?id=${VALID_ID}"; do
  expected="${route:-/}"
  headers="$(curl -sS -D - -o /dev/null -H "accept-language: de-DE,de;q=0.9" "${BASE}/en${route}" | tr -d '\r')"
  grep -q '^HTTP/[0-9.]* 302' <<<"${headers}" || fail "/en${route} is not a 302"
  location="$(grep -i '^location: ' <<<"${headers}" | cut -d' ' -f2-)"
  [ "${location}" = "${expected}" ] || fail "/en${route} redirects to '${location}' instead of ${expected}"
  if grep -qi '^vary:.*accept-language' <<<"${headers}"; then
    fail "/en${route}: the redirect varies by Accept-Language"
  fi
  grep -qi '^cache-control: no-store$' <<<"${headers}" || fail "/en${route}: the redirect may be cached"
  check_headers "/en${route}"
  echo "ok  /en${route} redirects to ${expected}"
done

# The view shell must not depend on the id, so a scanner cannot tell existing from
# absent.
for prefix in "" "/de"; do
  a="$(curl -fsS "${BASE}${prefix}/p/${VALID_ID}")"
  b="$(curl -fsS "${BASE}${prefix}/p/AAAAAAAAAAAAAAAAAAAAAA")"
  [ "${a}" = "${b}" ] || fail "the view shell under '${prefix}/p/' differs by paste id"
done
echo "ok  view shell is id independent"

for script in language-init.js theme-init.js; do
  headers="$(curl -fsS -D - -o /dev/null "${BASE}/${script}" | tr -d '\r')" || fail "/${script} missing from the binary"
  grep -qi '^content-type: text/javascript' <<<"${headers}" || fail "/${script} is not served as JavaScript"
  echo "ok  /${script}"
done

# The built-in favicon, which every page links unless one is configured.
headers="$(curl -fsS -D - -o /dev/null "${BASE}/favicon.svg" | tr -d '\r')" || fail "/favicon.svg missing from the binary"
grep -qi '^content-type: image/svg+xml' <<<"${headers}" || fail "/favicon.svg is not served as SVG"
check_headers "/favicon.svg"
echo "ok  /favicon.svg"

# --- API: a full lifecycle ---------------------------------------------------

API="${BASE}/api/v1/pastes"

REVEAL_TOKEN="smoke-reveal-token"
DELETE_SECRET="smoke-delete-secret"
DESCRIBE_TOKEN="smoke-describe-token"
PLAINTEXT_MARKER="SMOKE-CIPHERTEXT-MARKER"

REVEAL_VERIFIER="$(printf '%s' "${REVEAL_TOKEN}" | sha256_b64url)"
# The delete verifier is domain-separated, the reveal verifier is not.
DELETE_VERIFIER="$(printf 'capsule/v1/delete%s' "${DELETE_SECRET}" | sha256_b64url)"
DESCRIBE_VERIFIER="$(printf '%s' "${DESCRIBE_TOKEN}" | sha256_b64url)"

CIPHERTEXT_B64="$(printf '%s' "${PLAINTEXT_MARKER}" | b64url)"
HEADER_B64="$(printf 'public-header' | b64url)"

# Arguments: id (default VALID_ID) and, optionally, an explicit expiry in seconds.
create_body() {
  local id="${1:-${VALID_ID}}"
  local expiry=""
  [ -n "${2:-}" ] && expiry=",\"expires_in\":$2"

  printf '{"id":"%s","format_version":1,"public_header":"%s","ciphertext":"%s","reveal_verifier":"%s","delete_verifier":"%s","describe_verifier":"%s"%s}' \
    "${id}" "${HEADER_B64}" "${CIPHERTEXT_B64}" "${REVEAL_VERIFIER}" "${DELETE_VERIFIER}" "${DESCRIBE_VERIFIER}" "${expiry}"
}

# retrieve_body [reveal token]: a retrieve from someone holding the link - the
# describe token plus a reveal token (default: the right one).
retrieve_body() {
  printf '{"describe_token":"%s","reveal_token":"%s"}' \
    "$(printf '%s' "${DESCRIBE_TOKEN}" | b64url)" "$(printf '%s' "${1:-${REVEAL_TOKEN}}" | b64url)"
}

# describe <id> [token]: the descriptor, which needs the describe capability.
describe() {
  curl -sS -X POST "${API}/$1/describe" -H 'content-type: application/json' \
    --data "{\"describe_token\":\"$(printf '%s' "${2:-${DESCRIBE_TOKEN}}" | b64url)\"}"
}

# Creation without a token must be refused before anything else happens.
CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "${API}" \
  -H 'content-type: application/json' --data "$(create_body)")"
[ "${CODE}" = "401" ] || fail "creation without a token returned ${CODE} instead of 401"
echo "ok  creation without a token is refused"

# With the token it succeeds.
RESPONSE="$(curl -sS -X POST "${API}" \
  -H 'content-type: application/json' \
  -H "authorization: Bearer ${TOKEN}" \
  --data "$(create_body)")"
grep -q "\"id\":\"${VALID_ID}\"" <<<"${RESPONSE}" || fail "creation failed: ${RESPONSE}"
echo "ok  create"

# The descriptor returns the header and never the ciphertext.
DESCRIPTOR="$(describe "${VALID_ID}")"
grep -q "\"public_header\":\"${HEADER_B64}\"" <<<"${DESCRIPTOR}" ||
  fail "descriptor is missing the public header: ${DESCRIPTOR}"
if grep -q "${CIPHERTEXT_B64}" <<<"${DESCRIPTOR}"; then
  fail "the descriptor leaked the ciphertext"
fi
echo "ok  descriptor without ciphertext"

# Without the describe capability a known id looks exactly like an unknown one.
NO_CAP="$(describe "${VALID_ID}" wrong-token | sed 's/"request_id":"[^"]*"//')"
UNKNOWN="$(describe AAAAAAAAAAAAAAAAAAAAAA | sed 's/"request_id":"[^"]*"//')"
[ "${NO_CAP}" = "${UNKNOWN}" ] || fail "the descriptor tells a known id from an unknown one: ${NO_CAP} vs ${UNKNOWN}"
if grep -q 'burn_after_retrieval\|public_header' <<<"${NO_CAP}"; then
  fail "the descriptor leaked metadata without a capability: ${NO_CAP}"
fi
echo "ok  descriptor without the capability reveals nothing"

# The retrieval bookkeeping exists for the retention policy alone. In a response it
# would tell anyone holding the id whether and roughly when the link was used.
for field in last_retrieved_at retrieval_count; do
  if grep -q "${field}" <<<"${DESCRIPTOR}"; then
    fail "the descriptor exposes ${field}: ${DESCRIPTOR}"
  fi
done
echo "ok  descriptor without retrieval metadata"

# Retrieval with the right token returns the payload byte for byte.
RETRIEVED="$(curl -sS -X POST "${API}/${VALID_ID}/retrieve" \
  -H 'content-type: application/json' \
  --data "$(retrieve_body)")"
grep -q "\"ciphertext\":\"${CIPHERTEXT_B64}\"" <<<"${RETRIEVED}" ||
  fail "retrieval did not return the payload: ${RETRIEVED}"
echo "ok  retrieve"

# A wrong capability and an unknown id must be indistinguishable.
WRONG="$(curl -sS -X POST "${API}/${VALID_ID}/retrieve" \
  -H 'content-type: application/json' \
  --data "$(retrieve_body wrong)")"
ABSENT="$(curl -sS -X POST "${API}/AAAAAAAAAAAAAAAAAAAAAA/retrieve" \
  -H 'content-type: application/json' \
  --data "$(retrieve_body wrong)")"

WRONG_CODE="$(json_field code <<<"${WRONG}")"
ABSENT_CODE="$(json_field code <<<"${ABSENT}")"
[ "${WRONG_CODE}" = "not_available" ] || fail "wrong capability reported ${WRONG_CODE}"
[ "${ABSENT_CODE}" = "not_available" ] || fail "unknown id reported ${ABSENT_CODE}"
echo "ok  wrong capability and unknown id are indistinguishable"

# problem+json shape, using the configured base URL rather than the Host header.
PROBLEM="$(curl -sS -H 'host: evil.example' -X POST "${API}/AAAAAAAAAAAAAAAAAAAAAA/describe" \
  -H 'content-type: application/json' --data '{"describe_token":"eA"}')"
grep -q '"type":"https://paste.example/problems/not_available"' <<<"${PROBLEM}" ||
  fail "problem type is wrong or derived from the Host header: ${PROBLEM}"
grep -q '"request_id":"' <<<"${PROBLEM}" || fail "problem response has no request id: ${PROBLEM}"
echo "ok  problem+json shape"

CT="$(curl -sS -D - -o /dev/null -X POST "${API}/AAAAAAAAAAAAAAAAAAAAAA/describe" \
  -H 'content-type: application/json' --data '{"describe_token":"eA"}' | tr -d '\r' | grep -i '^content-type:')"
grep -qi 'application/problem+json' <<<"${CT}" || fail "wrong media type on an error: ${CT}"
echo "ok  problem+json media type"

# Deleting requires the delete secret; a reveal token must not work.
CODE="$(curl -s -o /dev/null -w '%{http_code}' -X DELETE "${API}/${VALID_ID}" \
  -H 'content-type: application/json' \
  --data "{\"delete_secret\":\"$(printf '%s' "${REVEAL_TOKEN}" | b64url)\"}")"
[ "${CODE}" = "404" ] || fail "a reveal token was accepted for deletion (${CODE})"
echo "ok  a reveal token cannot delete"

CODE="$(curl -s -o /dev/null -w '%{http_code}' -X DELETE "${API}/${VALID_ID}" \
  -H 'content-type: application/json' \
  --data "{\"delete_secret\":\"$(printf '%s' "${DELETE_SECRET}" | b64url)\"}")"
[ "${CODE}" = "204" ] || fail "deletion with the right secret returned ${CODE}"
echo "ok  delete"

# Gone afterwards, and generically so.
GONE="$(curl -sS -X POST "${API}/${VALID_ID}/retrieve" \
  -H 'content-type: application/json' \
  --data "$(retrieve_body)")"
[ "$(json_field code <<<"${GONE}")" = "not_available" ] ||
  fail "a deleted paste is still retrievable: ${GONE}"
echo "ok  deleted paste is gone"

# A retry of the identical create is answered like the original (ADR-011); the
# same id with different content stays a conflict.
REPLAY_ID="2pS3xQ7Rk9mNpLz4AbCdEg"
for attempt in first replay; do
  CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "${API}" \
    -H 'content-type: application/json' \
    -H "authorization: Bearer ${TOKEN}" \
    --data "$(create_body "${REPLAY_ID}" 3600)")"
  [ "${CODE}" = "201" ] || fail "${attempt} create returned ${CODE} instead of 201"
done
CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "${API}" \
  -H 'content-type: application/json' \
  -H "authorization: Bearer ${TOKEN}" \
  --data "$(create_body "${REPLAY_ID}" 7200)")"
[ "${CODE}" = "409" ] || fail "a create with different options returned ${CODE} instead of 409"
echo "ok  an identical create is a replay, a different one a conflict"

# The database must hold verifiers, never the secrets themselves. This is the
# file-level form of the promise that a database leak grants no rights: an attacker
# with the file still cannot retrieve or delete anything.
#
# Deliberately *not* asserted: that the ciphertext bytes are gone from the file
# after a delete. Setting a column to NULL frees the page without overwriting it,
# and the write-ahead log still holds the original insert. Physical erasure is not
# promised - only logical unavailability, which the checks above cover. Asserting
# it here would encode a guarantee the project does not make.
for secret in "${REVEAL_TOKEN}" "${DELETE_SECRET}" "${TOKEN}"; do
  if grep -qa -- "${secret}" "${WORKDIR}"/capsulebin.db* 2>/dev/null; then
    fail "a capability secret was written to the database file"
  fi
done
echo "ok  the database holds no capability secrets"

# --- CLI ---------------------------------------------------------------------
#
# The bundled CLI against the binary: client-side encryption from
# @capsulebin/core, the creation token from the environment, and the plaintext
# never reaching the database.

if [ -n "${CAPSULEBIN_CLI:-}" ]; then
  need node
  cli() {
    CAPSULEBIN_SERVER="${BASE}" CAPSULEBIN_TOKEN="${TOKEN}" node "${CAPSULEBIN_CLI}" "$@"
  }
  CLI_MARKER="SMOKE-CLI-PLAINTEXT-$$"
  CLI_DIR="${WORKDIR}/cli"
  mkdir -p "${CLI_DIR}"
  printf '# %s\n' "${CLI_MARKER}" >"${CLI_DIR}/note.md"
  printf '\x00\x01binary\xff' >"${CLI_DIR}/blob.bin"

  CREATED="$(cli put "${CLI_DIR}/note.md" "${CLI_DIR}/blob.bin" --expires 1h --json)" ||
    fail "cli put failed: ${CREATED}"
  SHARE_URL="$(json_field share_url <<<"${CREATED}")"
  DELETE_URL="$(json_field delete_url <<<"${CREATED}")"
  [ -n "${SHARE_URL}" ] && [ -n "${DELETE_URL}" ] || fail "cli put printed no links: ${CREATED}"
  echo "ok  cli put"

  cli get "${SHARE_URL}" -o "${CLI_DIR}/out" >/dev/null 2>&1 || fail "cli get failed"
  cmp -s "${CLI_DIR}/note.md" "${CLI_DIR}/out/note.md" || fail "cli get returned a different note"
  cmp -s "${CLI_DIR}/blob.bin" "${CLI_DIR}/out/blob.bin" || fail "cli get returned a different file"
  echo "ok  cli get round-trips text and binary items"

  if grep -qa -- "${CLI_MARKER}" "${WORKDIR}"/capsulebin.db* 2>/dev/null; then
    fail "plaintext from the CLI reached the database file"
  fi
  echo "ok  no CLI plaintext in the database"

  # Burn: exactly one retrieval. Afterwards the server answers like for any
  # unavailable capsule, so the CLI exits with 3 (not available).
  BURN_URL="$(printf 'once' | cli put --burn)" || fail "cli put --burn failed"
  [ "$(cli get "${BURN_URL}" --yes 2>/dev/null)" = "once" ] || fail "cli could not retrieve a burn capsule"
  set +e
  cli get "${BURN_URL}" --yes >/dev/null 2>&1
  CODE=$?
  set -e
  [ "${CODE}" = "3" ] || fail "a consumed burn capsule gave exit code ${CODE} instead of 3"
  echo "ok  cli burn-after-retrieval"

  cli delete "${DELETE_URL}" 2>/dev/null || fail "cli delete failed"
  set +e
  cli get "${SHARE_URL}" >/dev/null 2>&1
  CODE=$?
  set -e
  [ "${CODE}" = "3" ] || fail "a deleted capsule gave exit code ${CODE} instead of 3"
  echo "ok  cli delete"
else
  echo "--  CLI checks skipped (set CAPSULEBIN_CLI to the bundled cli.js)"
fi

# --- burn race ---------------------------------------------------------------
#
# Twenty clients retrieve the same burn-after-retrieval paste at once, over real
# connections into the real connection pool. Exactly one may get the payload.

RACE_ID="2pS3xQ7Rk9mNpLz4AbCdRA"
curl -s -o /dev/null -X POST "${API}" \
  -H 'content-type: application/json' -H "authorization: Bearer ${TOKEN}" \
  --data "$(create_body "${RACE_ID}" | sed 's/}$/,"burn_after_retrieval":true}/')"
RACE_DIR="$(mktemp -d -p "${WORKDIR}")"
RACE_PIDS=()
for n in $(seq 1 20); do
  curl -s -o /dev/null -w '%{http_code}' -X POST "${API}/${RACE_ID}/retrieve" \
    -H 'content-type: application/json' \
    --data "$(retrieve_body)" >"${RACE_DIR}/${n}" &
  RACE_PIDS+=("$!")
done
# Only these: a bare `wait` would also wait for the server.
wait "${RACE_PIDS[@]}"
WINNERS="$(cat "${RACE_DIR}"/* | grep -o '200' | wc -l)"
